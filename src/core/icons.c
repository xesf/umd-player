static void draw_bits(canvas *c, const char *const *rows, int x, int y, int scale, uint32_t rgba)
{
    for (int r = 0; r < ICON_SIZE; r++)
        for (int col = 0; col < ICON_SIZE && rows[r][col]; col++)
            if (rows[r][col] == '#')
                canvas_rect(c, x + col * scale, y + r * scale, scale, scale, rgba);
}

void canvas_icon(canvas *c, icon_id icon, int x, int y, int scale, uint32_t rgba)
{
    if (icon < 0 || icon >= ICON_COUNT || !icons[icon][0])
        return;
    draw_bits(c, icons[icon], x + 1, y + 1, scale, SHADOW);
    draw_bits(c, icons[icon], x, y, scale, rgba);
}

void canvas_battery(canvas *c, int x, int y, int w, int h, int percent, int charging, uint32_t rgba)
{
    int nub = h / 3, inner = w - 6, fill;
    uint32_t level = percent <= 15 ? RGBA(255, 90, 80, 255) : rgba;

    if (percent < 0)
        percent = 0;
    if (percent > 100)
        percent = 100;
    fill = inner * percent / 100;
    /* outline and the terminal nub */
    canvas_rect(c, x, y, w, 2, rgba);
    canvas_rect(c, x, y + h - 2, w, 2, rgba);
    canvas_rect(c, x, y, 2, h, rgba);
    canvas_rect(c, x + w - 2, y, 2, h, rgba);
    canvas_rect(c, x + w, y + (h - nub) / 2, 3, nub, rgba);
    canvas_rect(c, x + 3, y + 3, fill, h - 6, level);
    if (charging) {
        /* a small bolt in the middle */
        int cx = x + w / 2, cy = y + 3, hh = h - 6;
        uint32_t bolt = percent > 40 ? RGBA(20, 24, 40, 255) : RGBA(255, 220, 60, 255);
        for (int i = 0; i < hh; i++) {
            int off = i < hh / 2 ? (hh / 2 - i) / 2 : -((i - hh / 2) / 2);
            canvas_rect(c, cx + off - 1, cy + i, 3, 1, bolt);
        }
    }
}
